FIELDS=('product_name','price.amount','price.currency','rating')
def norm(x):return ' '.join(unicodedata.normalize('NFKC',str(x)).split()).casefold()
def quote_norm(x):return ' '.join(unicodedata.normalize('NFKC',str(x)).split())
def flat(record):
    if not isinstance(record,dict):return {}
    price=record.get('price')
    price=price if isinstance(price,dict) else {}
    return {k:v for k,v in {'product_name':record.get('product_name'),'price.amount':price.get('amount'),'price.currency':price.get('currency'),'rating':record.get('rating')}.items() if v is not None}
def equal(field,a,b):
    if field in ('price.amount','rating'):
        return type(a) in (int,float) and type(b) in (int,float) and abs(a-b)<1e-8
    if field=='price.currency':return isinstance(a,str) and isinstance(b,str) and a.upper()==b.upper()
    return isinstance(a,str) and isinstance(b,str) and norm(a)==norm(b)
def f1(tp,fp,fn):
    p=tp/(tp+fp) if tp+fp else 0.0;r=tp/(tp+fn) if tp+fn else 0.0
    return {'precision':p,'recall':r,'f1':2*p*r/(p+r) if p+r else 0.0}
_PATH_COMPONENT = re.compile(r'^([A-Za-z][A-Za-z0-9_-]*):nth-of-type\((\d+)\)$')

def css_path_to_xpath(css):
    # Experimental provenance CSS is intentionally restricted to the deterministic
    # absolute nth-of-type grammar generated by selector_paths().  Converting that
    # grammar directly avoids selector-engine differences during scoring.
    if not isinstance(css,str) or not css.strip():
        raise ValueError('empty CSS path')
    parts=[]
    for component in css.split(' > '):
        m=_PATH_COMPONENT.fullmatch(component.strip())
        if not m:
            raise ValueError(f'unsupported CSS provenance grammar: {component}')
        parts.append(f'{m.group(1).lower()}[{int(m.group(2))}]')
    return '/' + '/'.join(parts)

def locate(doc,e):
    try:
        xp=doc.xpath(e['xpath'])
        css_equiv=doc.xpath(css_path_to_xpath(e['css']))
        if len(css_equiv)==len(xp)==1 and css_equiv[0] is xp[0]:
            return xp[0]
    except Exception:
        pass
    return None

def record_card(doc,r,cards):
    if not isinstance(r,dict):return None
    ev=r.get('evidence');ev=ev if isinstance(ev,dict) else {}
    e=ev.get('product_name');n=locate(doc,e) if isinstance(e,dict) else None
    if n is None:return None
    return next((i for i,c in enumerate(cards) if n is c or c in n.iterancestors()),None)

def align(pred,gold,doc,cards):
    # Maximum cardinality exact-name matching; provenance disambiguates duplicate
    # names, then equal field counts, then deterministic input order.
    dp={0:(0,[])}
    for pi,p in enumerate(pred):
        if not isinstance(p,dict):continue
        candidates=[j for j,g in enumerate(gold) if equal('product_name',p.get('product_name'),g['product_name'])]
        card=record_card(doc,p,cards);next_dp=dict(dp)
        for mask,(score,pairs) in dp.items():
            for j in candidates:
                if mask>>j&1:continue
                weight=100000+(1000 if card==j else 0)+sum(equal(k,v,flat(gold[j]).get(k)) for k,v in flat(p).items())
                new=mask|1<<j
                if new not in next_dp or score+weight>next_dp[new][0]:next_dp[new]=(score+weight,pairs+[(pi,j)])
        dp=next_dp
    return max(dp.values(),key=lambda x:x[0])[1]

def support(doc,r,field,gold_record,card):
    group='price' if field.startswith('price.') else field
    ev=r.get('evidence',{}) if isinstance(r,dict) else {}
    e=ev.get(group) if isinstance(ev,dict) else None
    if not isinstance(e,dict):return False,False,False
    n=locate(doc,e)
    located=n is not None
    if not located:return False,False,False
    inside=n is card or card in n.iterancestors()
    attr=e.get('attribute')
    if attr not in (None,'aria-label','aria-description','title','alt','content'):return True,False,False
    actual=n.get(attr,'') if attr else n.text_content()
    quote=e.get('text_quote','')
    quoted=isinstance(quote,str) and bool(quote.strip()) and quote_norm(quote)==quote_norm(actual)
    correct=field in flat(r) and field in flat(gold_record) and equal(field,flat(r)[field],flat(gold_record)[field])
    if group not in gold_record['evidence']:return True,quoted,False
    canonical=locate(doc,gold_record['evidence'][group])
    canonical_actual=canonical.get(gold_record['evidence'][group]['attribute'],'') if gold_record['evidence'][group]['attribute'] else canonical.text_content()
    # Equivalent text nodes are allowed (e.g. visible and accessibility price spans).
    # Broad containers that mix old and new prices cannot support a field.
    same_source=(n is canonical or (n in canonical.iterdescendants()))
    equivalent=quote_norm(actual)==quote_norm(canonical_actual)
    if group=='price':
        def price_text(x):return quote_norm(x).replace('–','00').replace('−','00').replace(' ','')
        equivalent=price_text(actual)==price_text(canonical_actual)
    if group=='product_name':equivalent=norm(actual)==norm(gold_record['product_name'])
    verified=inside and quoted and correct and (same_source or equivalent)
    return True,quoted,verified

def score(prediction,gold,doc,site_cfg,metadata=None):
    schema=read_json(ROOT/'schema/output.schema.json')
    errors=list(Draft202012Validator(schema).iter_errors(prediction))
    pred=prediction.get('records',[]) if isinstance(prediction,dict) else []
    pred=pred if isinstance(pred,list) else []
    cards=select_cards(doc,site_cfg['card_selector'])[:site_cfg['limit']]
    pairs=align(pred,gold,doc,cards);pmap=dict(pairs)
    gold_n=sum(len(flat(g)) for g in gold);pred_n=sum(len(flat(p)) for p in pred)
    tp=0;located=quoted=verified=0;details=[];complete=0;null_correct=0
    for pi,gi in pairs:
        p,g=pred[pi],gold[gi]
        hit=sum(equal(k,v,flat(g).get(k)) for k,v in flat(p).items())
        tp+=hit;complete+=int(hit==len(flat(g)) and set(flat(p))==set(flat(g)))
        null_correct+=int(g['rating'] is None and 'rating' in p and p['rating'] is None)
    # Selector / quote coverage counts for all claims; verified support requires a matched record.
    for pi,p in enumerate(pred):
        for field,value in flat(p).items():
            gi=pmap.get(pi)
            if gi is not None:a,b,c=support(doc,p,field,gold[gi],cards[gi])
            else:
                ev=p.get('evidence',{}) if isinstance(p,dict) else {};e=ev.get('price' if field.startswith('price.') else field,{}) if isinstance(ev,dict) else {}
                n=locate(doc,e);a=n is not None;b=c=False
                if a:
                    attr=e.get('attribute');actual=n.get(attr,'') if attr in ('aria-label','aria-description','title','alt','content') else n.text_content()
                    b=bool(e.get('text_quote')) and quote_norm(e.get('text_quote'))==quote_norm(actual)
            located+=int(a);quoted+=int(b);verified+=int(c)
            details.append({'prediction_index':pi,'gold_index':gi,'field':field,'selector_pair_valid':a,'quote_valid':b,'supported_correct_value':c})
    fp=pred_n-tp;fn=gold_n-tp;fm=f1(tp,fp,fn);rm=f1(len(pairs),len(pred)-len(pairs),len(gold)-len(pairs))
    extras=0
    for p in pred:
        if not isinstance(p,dict):continue
        extras+=len(set(p)-{'product_name','price','rating','evidence'})
        if isinstance(p.get('price'),dict):extras+=len(set(p['price'])-{'amount','currency'})
    md=metadata or {}
    row={'strict_field_f1':fm['f1'],'strict_field_precision':fm['precision'],'strict_field_recall':fm['recall'],'field_tp':tp,'field_fp':fp,'field_fn':fn,'record_precision':rm['precision'],'record_recall':rm['recall'],'record_f1':rm['f1'],'matched_records':len(pairs),'predicted_records':len(pred),'gold_records':len(gold),'record_completeness':complete/len(gold) if gold else 0,'schema_adherence':int(not errors),'schema_error_count':len(errors),'non_schema_field_count':extras,'selector_pair_coverage':located/pred_n if pred_n else 0,'quote_coverage':quoted/pred_n if pred_n else 0,'verified_provenance_precision':verified/pred_n if pred_n else 0,'verified_provenance_recall':verified/gold_n if gold_n else 0,'supported_field_count':verified,'unsupported_field_count':pred_n-verified,'null_rating_accuracy':null_correct/sum(g['rating'] is None for g in gold) if any(g['rating'] is None for g in gold) else None,'latency_seconds':md.get('latency_seconds',0),'input_tokens':md.get('input_tokens',0),'output_tokens':md.get('output_tokens',0),'browser_actions':md.get('browser_actions',0),'tool_actions':md.get('tool_actions',0)}
    row['task_success']=int(rm['recall']>=0.90 and fm['f1']>=0.85 and not errors)
    return row,{'alignment':pairs,'fields':details,'schema_errors':[e.message for e in errors]}

def write_csv(path,rows):
    if not rows:return
    with Path(path).open('w',newline='',encoding='utf-8-sig') as f:
        writer=csv.DictWriter(f,fieldnames=list(dict.fromkeys(k for r in rows for k in r)))
        writer.writeheader();writer.writerows(rows)

def evaluate(allow_partial=False,run_root=None,result_root=None):
    frozen=verify_freeze();cfg=config();run_root=Path(run_root or ROOT/'runs');result_root=Path(result_root or ROOT/'results');result_root.mkdir(exist_ok=True,parents=True)
    rows=[];missing=[];schedule=read_json(ROOT/'execution_schedule.json')
    for e in schedule:
        p=run_root/e['agent']/e['site']/f'run_{e["rep"]:02d}'
        if not (p/'metadata.json').exists():missing.append(e);continue
        md=read_json(p/'metadata.json')
        if not md.get('finished'):raise RuntimeError(f'Interrupted run needs resume: {p}')
        if md.get('freeze_sha256')!=frozen:raise RuntimeError(f'Run belongs to a different freeze: {p}')
        if md.get('output_sha256') and digest(p/'output.json')!=md['output_sha256']:raise RuntimeError(f'Output was modified after the run: {p}')
        prediction=read_json(p/'output.json') if (p/'output.json').exists() else {'records':[]}
        gold=read_json(ROOT/'gold'/f'{e["site"]}.json')['records']
        doc=html.fromstring((ROOT/'snapshots'/e['site']/'index.html').read_text(encoding='utf-8'))
        row,detail=score(prediction,gold,doc,cfg['sites'][e['site']],md)
        if md.get('status')!='completed':row['task_success']=0
        acfg=cfg['agents'][e['agent']];arch_id=acfg['architecture'];model_key=acfg['model_key']
        row={**e,'architecture':arch_id,'architecture_name':cfg['architectures'][arch_id]['name'],'model_key':model_key,'model':cfg['models'][model_key]['model'],'status':md.get('status'),**row};rows.append(row)
        write_json(result_root/f'{e["agent"]}_{e["site"]}_{e["rep"]}_details.json',detail)
    if missing and not allow_partial:raise RuntimeError(f'{len(missing)} runs have not finished. Resume run-all; use --allow-partial only for diagnostics.')
    write_csv(result_root/'per_run_scores.csv',rows)
    metrics=['strict_field_f1','record_f1','record_recall','record_completeness','schema_adherence','task_success','selector_pair_coverage','quote_coverage','verified_provenance_precision','verified_provenance_recall','latency_seconds','input_tokens','output_tokens','tool_actions','browser_actions']
    site_rows=[];summary=[]
    expected_per_agent=len(cfg['sites'])*cfg['repetitions']
    for agent in cfg['agents']:
        ar=[r for r in rows if r['agent']==agent]
        if not ar:continue
        acfg=cfg['agents'][agent];arch_id=acfg['architecture'];model_key=acfg['model_key']
        for site in cfg['sites']:
            sr=[r for r in ar if r['site']==site]
            if not sr:continue
            out={'agent':agent,'architecture':arch_id,'model_key':model_key,'site':site,'n_runs':len(sr)}
            for metric in metrics:
                vals=[r[metric] for r in sr];out[metric+'_mean']=statistics.mean(vals);out[metric+'_std']=statistics.stdev(vals) if len(vals)>1 else 0
            site_rows.append(out)
        out={'agent':agent,'architecture':arch_id,'architecture_name':cfg['architectures'][arch_id]['name'],'model_key':model_key,'model':cfg['models'][model_key]['model'],'n_runs':len(ar),'complete':len(ar)==expected_per_agent}
        for metric in metrics:
            vals=[r[metric] for r in ar];out[metric+'_mean']=statistics.mean(vals);out[metric+'_std']=statistics.stdev(vals) if len(vals)>1 else 0
        mf=f1(sum(r['field_tp'] for r in ar),sum(r['field_fp'] for r in ar),sum(r['field_fn'] for r in ar));out['strict_field_f1_micro']=mf['f1']
        sites=sorted({r['site'] for r in ar});rng=random.Random(42);samples=[]
        for _ in range(2000):
            draws=[rng.choice(sites) for _ in sites]
            samples.append(statistics.mean([r['strict_field_f1'] for st in draws for r in ar if r['site']==st]))
        samples.sort();out['field_f1_cluster_ci_low']=samples[49];out['field_f1_cluster_ci_high']=samples[1949]
        summary.append(out)
    write_csv(result_root/'per_site_per_agent.csv',site_rows);write_csv(result_root/'summary_table.csv',summary)

    arch_rows=[]
    for arch in cfg['architectures']:
        rr=[r for r in rows if r['architecture']==arch]
        if rr:
            arch_rows.append({'architecture':arch,'architecture_name':cfg['architectures'][arch]['name'],'n_runs':len(rr),
                              'strict_field_f1_mean':statistics.mean(r['strict_field_f1'] for r in rr),
                              'record_f1_mean':statistics.mean(r['record_f1'] for r in rr),
                              'verified_provenance_precision_mean':statistics.mean(r['verified_provenance_precision'] for r in rr),
                              'task_success_mean':statistics.mean(r['task_success'] for r in rr),
                              'latency_seconds_mean':statistics.mean(r['latency_seconds'] for r in rr)})
    model_rows=[]
    for mk in cfg['models']:
        rr=[r for r in rows if r['model_key']==mk]
        if rr:
            model_rows.append({'model_key':mk,'model':cfg['models'][mk]['model'],'n_runs':len(rr),
                               'strict_field_f1_mean':statistics.mean(r['strict_field_f1'] for r in rr),
                               'record_f1_mean':statistics.mean(r['record_f1'] for r in rr),
                               'verified_provenance_precision_mean':statistics.mean(r['verified_provenance_precision'] for r in rr),
                               'task_success_mean':statistics.mean(r['task_success'] for r in rr),
                               'latency_seconds_mean':statistics.mean(r['latency_seconds'] for r in rr)})
    write_csv(result_root/'summary_by_architecture.csv',arch_rows);write_csv(result_root/'summary_by_model.csv',model_rows)
    write_json(result_root/'evaluation_manifest.json',{'freeze_sha256':frozen,'scheduled_runs':len(schedule),'scored_runs':len(rows),'missing_runs':missing,'partial':bool(missing),'design':'3 architectures x 3 LLMs x 4 sites x 3 repetitions = 108 runs','confidence_interval':'95% percentile, 2000 site-cluster bootstrap resamples, seed=42; only four sites; exploratory.'})
    report=['# R1 headphone extraction results','',f'Scored {len(rows)}/{len(schedule)} runs. '+('PARTIAL diagnostic results.' if missing else 'Complete scheduled experiment.'),'',
            '**Design:** 3 distinct agent architectures × 3 LLM backends = 9 architecture-model configurations.','',
            '| Agent config | Architecture | Model | Runs | Field F1 (macro) | Field F1 (micro) | Task success | Verified provenance precision |',
            '|---|---|---|---:|---:|---:|---:|---:|']
    for r in summary:
        report.append(f'| {r["agent"]} | {r["architecture"]} | {r["model"]} | {r["n_runs"]} | {r["strict_field_f1_mean"]:.4f} | {r["strict_field_f1_micro"]:.4f} | {r["task_success_mean"]:.4f} | {r["verified_provenance_precision_mean"]:.4f} |')
    report+=['','A1 is a direct frozen-DOM snapshot agent; A2 is a two-stage schema-state ground-and-verify agent; A3 is an iterative Playwright-MCP ReAct agent. All three architectures are evaluated with the same Gemma, Qwen, and Kimi model set. See docs/PROTOCOL.md.']
    (result_root/'REPORT.md').write_text('\n'.join(report),encoding='utf-8')
    return summary
